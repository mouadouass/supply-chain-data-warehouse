-- DIMENSION ENTREPÔT : pas d'historisation (les entrepôts ne changent pas), valeur la plus récente.
DROP TABLE IF EXISTS gold.dim_warehouse CASCADE;
CREATE TABLE gold.dim_warehouse (
    warehouse_key  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_id   text NOT NULL,
    warehouse_name text NOT NULL,
    city           text NOT NULL,
    region         text NOT NULL,
    capacity_units integer
);

INSERT INTO gold.dim_warehouse (warehouse_id, warehouse_name, city, region, capacity_units)
SELECT DISTINCT ON (warehouse_id) warehouse_id, warehouse_name, city, region, capacity_units
FROM silver.warehouses ORDER BY warehouse_id, batch_id DESC;

CREATE INDEX ON gold.dim_warehouse (warehouse_id);