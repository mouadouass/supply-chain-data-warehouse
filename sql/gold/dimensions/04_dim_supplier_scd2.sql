-- DIMENSION FOURNISSEUR, historisée (SCD Type 2) sur la VILLE.
-- Exemple : S002 déménage de Marrakech à Rabat. Il aura 2 lignes :
--   Marrakech : 1900-01-01 -> 2026-09-30     Rabat : 2026-10-01 -> 9999-12-31
DROP TABLE IF EXISTS gold.dim_supplier CASCADE;
CREATE TABLE gold.dim_supplier (
    supplier_key            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id             text    NOT NULL,
    supplier_name           text    NOT NULL,
    city                    text    NOT NULL,
    country                 text    NOT NULL,
    standard_lead_time_days integer,
    start_date              date    NOT NULL,
    end_date                date    NOT NULL,
    is_current              boolean NOT NULL
);

INSERT INTO gold.dim_supplier (supplier_id, supplier_name, city, country, standard_lead_time_days,
                               start_date, end_date, is_current)
WITH flagged AS (
    SELECT supplier_id, batch_id, city,
           CASE WHEN city IS DISTINCT FROM lag(city) OVER w THEN 1 ELSE 0 END AS changed
    FROM silver.suppliers
    WINDOW w AS (PARTITION BY supplier_id ORDER BY batch_id)
), numbered AS (
    SELECT *, sum(changed) OVER (PARTITION BY supplier_id ORDER BY batch_id) AS version_no FROM flagged
), versions AS (
    SELECT supplier_id, version_no, city, min(batch_id) AS first_batch FROM numbered GROUP BY 1, 2, 3
), bounds AS (
    SELECT *, CASE WHEN version_no = 1 THEN DATE '1900-01-01'
                   ELSE gold.lot_data_date(first_batch) END AS start_date
    FROM versions
), latest AS (
    SELECT DISTINCT ON (supplier_id) supplier_id, supplier_name, country, standard_lead_time_days
    FROM silver.suppliers ORDER BY supplier_id, batch_id DESC
)
SELECT b.supplier_id, l.supplier_name, b.city, l.country, l.standard_lead_time_days, b.start_date,
       coalesce(lead(b.start_date) OVER w2 - 1, DATE '9999-12-31'),
       lead(b.start_date) OVER w2 IS NULL
FROM bounds b JOIN latest l USING (supplier_id)
WINDOW w2 AS (PARTITION BY b.supplier_id ORDER BY b.version_no)
ORDER BY b.supplier_id, b.version_no;

CREATE INDEX ON gold.dim_supplier (supplier_id, start_date, end_date);