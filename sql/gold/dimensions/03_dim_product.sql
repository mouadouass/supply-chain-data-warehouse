-- DIMENSION PRODUIT, historisée (SCD Type 2) sur la CATÉGORIE.
DROP TABLE IF EXISTS gold.dim_product CASCADE;
CREATE TABLE gold.dim_product (
    product_key  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id   text    NOT NULL,
    product_name text    NOT NULL,
    category     text    NOT NULL,
    brand        text    NOT NULL,
    unit_price   numeric(12,2),              -- prix catalogue actuel
    supplier_id  text    NOT NULL,
    created_date date,
    start_date   date    NOT NULL,
    end_date     date    NOT NULL,
    is_current   boolean NOT NULL
);

INSERT INTO gold.dim_product (product_id, product_name, category, brand, unit_price, supplier_id,
                              created_date, start_date, end_date, is_current)
WITH flagged AS (
    SELECT product_id, batch_id, category,
           CASE WHEN category IS DISTINCT FROM lag(category) OVER w THEN 1 ELSE 0 END AS changed
    FROM silver.products
    WINDOW w AS (PARTITION BY product_id ORDER BY batch_id)
), numbered AS (
    SELECT *, sum(changed) OVER (PARTITION BY product_id ORDER BY batch_id) AS version_no FROM flagged
), versions AS (
    SELECT product_id, version_no, category, min(batch_id) AS first_batch FROM numbered GROUP BY 1, 2, 3
), bounds AS (
    SELECT *, CASE WHEN version_no = 1 THEN DATE '1900-01-01'
                   ELSE gold.lot_data_date(first_batch) END AS start_date
    FROM versions
), latest AS (
    SELECT DISTINCT ON (product_id) product_id, product_name, brand, unit_price, supplier_id, created_date
    FROM silver.products ORDER BY product_id, batch_id DESC
)
SELECT b.product_id, l.product_name, b.category, l.brand, l.unit_price, l.supplier_id,
       l.created_date, b.start_date,
       coalesce(lead(b.start_date) OVER w2 - 1, DATE '9999-12-31'),
       lead(b.start_date) OVER w2 IS NULL
FROM bounds b JOIN latest l USING (product_id)
WINDOW w2 AS (PARTITION BY b.product_id ORDER BY b.version_no)
ORDER BY b.product_id, b.version_no;

CREATE INDEX ON gold.dim_product (product_id, start_date, end_date);