-- DIMENSION CLIENT, historisée (SCD Type 2) sur la RÉGION.
-- Les autres attributs (nom, ville, e-mail...) prennent toujours la valeur la plus récente.
DROP TABLE IF EXISTS gold.dim_customer CASCADE;
CREATE TABLE gold.dim_customer (
    customer_key      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id       text    NOT NULL,
    customer_name     text    NOT NULL,
    customer_type     text    NOT NULL,
    email             text,
    city              text    NOT NULL,
    region            text    NOT NULL,
    registration_date date,
    start_date        date    NOT NULL,      -- début de validité de cette version
    end_date          date    NOT NULL,      -- fin de validité (9999-12-31 = version actuelle)
    is_current        boolean NOT NULL
);

INSERT INTO gold.dim_customer (customer_id, customer_name, customer_type, email, city, region,
                               registration_date, start_date, end_date, is_current)
WITH flagged AS (       -- 1. repérer chaque changement de région
    SELECT customer_id, batch_id, region,
           CASE WHEN region IS DISTINCT FROM lag(region) OVER w THEN 1 ELSE 0 END AS changed
    FROM silver.customers
    WINDOW w AS (PARTITION BY customer_id ORDER BY batch_id)
), numbered AS (        -- 2. numéroter les versions
    SELECT *, sum(changed) OVER (PARTITION BY customer_id ORDER BY batch_id) AS version_no
    FROM flagged
), versions AS (        -- 3. une ligne par version
    SELECT customer_id, version_no, region, min(batch_id) AS first_batch
    FROM numbered GROUP BY 1, 2, 3
), bounds AS (          -- 4. dates de début
    SELECT *, CASE WHEN version_no = 1 THEN DATE '1900-01-01'
                   ELSE gold.lot_data_date(first_batch) END AS start_date
    FROM versions
), latest AS (          -- valeurs les plus récentes des autres attributs
    SELECT DISTINCT ON (customer_id) customer_id, customer_name, customer_type, email, city,
           registration_date
    FROM silver.customers ORDER BY customer_id, batch_id DESC
)
SELECT b.customer_id, l.customer_name, l.customer_type, l.email, l.city, b.region,
       l.registration_date, b.start_date,
       coalesce(lead(b.start_date) OVER w2 - 1, DATE '9999-12-31'),   -- 5. fin = veille de la version suivante
       lead(b.start_date) OVER w2 IS NULL
FROM bounds b JOIN latest l USING (customer_id)
WINDOW w2 AS (PARTITION BY b.customer_id ORDER BY b.version_no)
ORDER BY b.customer_id, b.version_no;

CREATE INDEX ON gold.dim_customer (customer_id, start_date, end_date);